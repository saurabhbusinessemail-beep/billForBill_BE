'use strict';
const express = require('express');
const c = require('../controllers/businessPeopleTeams.controller');
const { requireSession } = require('../middleware/requireSession');
const router = express.Router();
router.use(requireSession);
router.get('/:businessId/overview', c.overview);
router.get('/:businessId/people/lookup', c.lookupPerson);
router.get('/:businessId/people', c.listPeople);
router.post('/:businessId/people', c.addPerson);
router.delete('/:businessId/people/:userId', c.removePerson);
router.get('/:businessId/teams', c.listTeams);
router.post('/:businessId/teams', c.createTeam);
router.get('/:businessId/teams/:teamId', c.getTeam);
router.patch('/:businessId/teams/:teamId', c.updateTeam);
router.delete('/:businessId/teams/:teamId', c.deleteTeam);
router.get('/:businessId/teams/:teamId/members', c.listTeamMembers);
router.put('/:businessId/teams/:teamId/members/:userId', c.addTeamMember);
router.delete('/:businessId/teams/:teamId/members/:userId', c.removeTeamMember);
router.get('/:businessId/permissions', c.permissionCatalog);
router.get('/:businessId/teams/:teamId/permissions', c.listTeamPermissions);
router.put('/:businessId/teams/:teamId/permissions', c.setTeamPermissions);
module.exports = router;
