'use strict';
const express = require('express');
const { requireSession } = require('../middleware/requireSession');
const controller = require('../controllers/businessBillsPayments.controller');
const router = express.Router();
const billFile = express.raw({ type: ['image/jpeg', 'image/png', 'application/pdf', 'application/octet-stream'], limit: '20mb' });
router.use(requireSession, (_req, res, next) => { res.setHeader('Cache-Control', 'private, no-store'); next(); });
router.get('/:businessId/incoming-bills', controller.listIncomingBills);
router.get('/:businessId/incoming-bills/:billId', controller.getIncomingBill);
router.get('/:businessId/incoming-bills/:billId/files/:fileId', controller.incomingBillFile);
router.get('/:businessId/bills/summary', controller.summary);
router.get('/:businessId/bills/parties/lookup', controller.lookupParty);
router.get('/:businessId/bills', controller.listBills);
router.post('/:businessId/bills', controller.createBill);
router.put('/:businessId/bills/:billId', controller.updateDraft);
router.get('/:businessId/bills/:billId', controller.getBill);
router.post('/:businessId/bills/:billId/issue', controller.issueBill);
router.post('/:businessId/bills/:billId/cancel', controller.cancelBill);
router.post('/:businessId/bills/:billId/files', billFile, controller.uploadFile);
router.get('/:businessId/bills/:billId/files/:fileId', controller.file);
router.post('/:businessId/bills/:billId/delivery', controller.delivery);
router.delete('/:businessId/bills/:billId', controller.deleteDraft);
router.get('/:businessId/payments/summary', controller.paymentSummary);
router.get('/:businessId/payments/party-balances', controller.listPartyBalances);
router.get('/:businessId/payments/pending-bills', controller.pendingBills);
router.get('/:businessId/payments', controller.listPayments);
router.get('/:businessId/payments/:paymentId', controller.getPayment);
router.post('/:businessId/payments', controller.createPayment);
router.post('/:businessId/payments/:paymentId/reverse', controller.reversePayment);
router.get('/:businessId/payment-method-config', controller.getMethodConfig);
router.put('/:businessId/payment-method-config', controller.saveMethodConfig);
router.get('/:businessId/document-number-config', controller.getNumberConfig);
router.put('/:businessId/document-number-config', controller.saveNumberConfig);
router.get('/:businessId/transport-config', controller.getTransportConfig);
router.put('/:businessId/transport-config', controller.saveTransportConfig);
module.exports = router;
