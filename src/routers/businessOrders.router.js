'use strict';
const express = require('express');
const { requireSession } = require('../middleware/requireSession');
const controller = require('../controllers/businessOrders.controller');
const router = express.Router();
const image = express.raw({ type: ['image/jpeg', 'image/png', 'image/webp', 'application/octet-stream'], limit: '20mb' });
router.use(requireSession, (_req, res, next) => { res.setHeader('Cache-Control', 'private, no-store'); next(); });
router.get('/:businessId/orders/summary', controller.summary);
router.get('/:businessId/orders/options', controller.options);
router.get('/:businessId/orders/products/search', controller.searchProducts);
router.get('/:businessId/orders/contacts/lookup', controller.lookupContact);
router.post('/:businessId/orders/taxes', controller.addTax);
router.get('/:businessId/orders', controller.list);
router.post('/:businessId/orders/image-only', image, controller.createImage);
router.post('/:businessId/orders', controller.create);
router.get('/:businessId/orders/:orderId', controller.get);
router.patch('/:businessId/orders/:orderId', controller.update);
router.post('/:businessId/orders/:orderId/actions', controller.transition);
router.delete('/:businessId/orders/:orderId', controller.remove);
router.post('/:businessId/orders/:orderId/images', image, controller.attachImage);
router.get('/:businessId/orders/:orderId/images/:imageId', controller.image);
router.delete('/:businessId/orders/:orderId/images/:imageId', controller.removeImage);
router.delete('/:businessId/orders/:orderId/image-upload', controller.abortImageOrder);
module.exports = router;
